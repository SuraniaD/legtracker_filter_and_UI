def upgrade() -> None:
    # pgvector >= 0.5 is needed for the HNSW index below. CREATE EXTENSION
    # needs a role allowed to create extensions; if that fails, ask the DB
    # owner to run it once.
    op.execute("CREATE EXTENSION IF NOT EXISTS vector")
    op.execute("CREATE SCHEMA IF NOT EXISTS tracker")

    # ── Reference ────────────────────────────────────────────────────────────
    op.execute("""
        CREATE TABLE tracker.subject_categories (
            subject_name  text PRIMARY KEY,
            category      text    NOT NULL,
            active        boolean NOT NULL DEFAULT true
        )
    """)
    values = ",\n".join(
        "('{}', '{}')".format(name.replace("'", "''"), cat.replace("'", "''"))
        for name, cat in SUBJECT_SEED
    )
    op.execute(f"INSERT INTO tracker.subject_categories (subject_name, category) VALUES\n{values}")

    # ── Category 1: filtered bills (filled by the filter job) ────────────────
    op.execute("""
        CREATE TABLE tracker.bills (
            id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            raw_bill_id          integer NOT NULL,          -- public.bills.id (no FK on purpose)
            source_id            text    NOT NULL,          -- '119-HR-1085'
            congress             integer NOT NULL,
            bill_type            text    NOT NULL,          -- uppercase, as in public.bills
            bill_number          integer NOT NULL,
            title                text,
            official_title       text,
            introduced_date      date,
            origin_chamber       text,                      -- 'House' / 'Senate'
            policy_area          text,
            last_action_date     date,
            last_action_text     text,
            source_url           text,                      -- public congress.gov page
            official_summary     text,                      -- latest CRS summary, plain text
            sponsor_bioguide_id  text,
            sponsor_name         text,
            sponsor_party        text,
            sponsor_state        text,
            matched_rule         text    NOT NULL
                CHECK (matched_rule IN ('policy_area', 'subject', 'keyword', 'committee', 'semantic')),
            prefilter_score      integer,                   -- gate 3 score, when it ran
            content_hash         text    NOT NULL,          -- triggers AI re-run when it changes
            raw_updated_at       timestamp,                 -- public.bills.update_date_including_text
            filtered_at          timestamp NOT NULL DEFAULT now(),
            updated_at           timestamp NOT NULL DEFAULT now(),
            CONSTRAINT uq_tracker_bills_raw_bill_id UNIQUE (raw_bill_id),
            CONSTRAINT uq_tracker_bills_source_id   UNIQUE (source_id),
            CONSTRAINT uq_tracker_bills_identity    UNIQUE (congress, bill_type, bill_number)
        )
    """)
    op.execute("CREATE INDEX ix_tracker_bills_last_action_date ON tracker.bills (last_action_date DESC)")
    op.execute("CREATE INDEX ix_tracker_bills_introduced_date  ON tracker.bills (introduced_date DESC)")
    op.execute("CREATE INDEX ix_tracker_bills_policy_area      ON tracker.bills (policy_area)")
    op.execute("CREATE INDEX ix_tracker_bills_bill_type        ON tracker.bills (bill_type)")
    op.execute("CREATE INDEX ix_tracker_bills_congress         ON tracker.bills (congress)")

    op.execute("""
        CREATE TABLE tracker.bill_actions (
            id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            bill_id         bigint NOT NULL REFERENCES tracker.bills (id) ON DELETE CASCADE,
            action_date     date,
            action_text     text,
            action_type     text,
            action_code     text,
            source_system   text
        )
    """)
    # Replaced per bill with delete-then-insert, like public.bill_action.
    op.execute("CREATE INDEX ix_tracker_bill_actions_bill_date ON tracker.bill_actions (bill_id, action_date DESC)")
    op.execute("CREATE INDEX ix_tracker_bill_actions_date      ON tracker.bill_actions (action_date)")

